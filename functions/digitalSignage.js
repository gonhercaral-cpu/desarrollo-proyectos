// Digital Signage capabilities are independent of user and Classroom identities.
// Only hashes of technical credentials are persisted; all control data is private.
const { createHash, randomInt, randomUUID } = require("node:crypto");

const PAIRS = "digitalSignageControlPairings";
const RUNTIME = "digitalSignageControl";
const IDENTITIES = "digitalSignageControlIdentities";
const DEVICES = "digitalSignageDevices";
const TTL = 120000;
const LEASE = 45000;
const CONNECTION_MAX_AGE_MS = 120000;
const TERMINAL = new Set(["executed", "failed", "expired"]);
const TYPES = new Set(["refresh", "web_reload", "web_scroll", "web_navigate"]);
const hash = (value) => createHash("sha256").update(value).digest("hex");
const text = (value, max = 300) => String(value || "").slice(0, max);

function createSignageHandlers({ db, FieldValue, HttpsError, now = Date.now }) {
  function fail(code, message) { throw new HttpsError(code, message); }
  function id(value) {
    if (typeof value !== "string" || !/^[A-Za-z0-9_-]{1,128}$/.test(value)) {
      fail("invalid-argument", "Identificador inválido.");
    }
    return value;
  }
  function credential(value) {
    if (typeof value !== "string" || !/^ds2_[a-f0-9]{64}$/.test(value)) {
      fail("permission-denied", "Revincula la pantalla para habilitar el control seguro.");
    }
    return hash(value);
  }
  async function admin(request) {
    if (!request.auth?.uid || request.auth.token?.activeClassroomDevice === true) {
      fail("permission-denied", "Se requiere un administrador activo.");
    }
    const profile = (await db.collection("users").doc(request.auth.uid).get()).data();
    if (profile?.active !== true || String(profile.role).trim().toLowerCase() !== "admin") {
      fail("permission-denied", "Se requiere un administrador activo.");
    }
    return request.auth.uid;
  }
  function audit(tx, action, deviceId, uid, details = {}) {
    tx.create(db.collection("digitalSignageAuditLogs").doc(), {
      action, entityType: "device", entityId: deviceId, entityName: deviceId,
      details, createdById: uid, createdBy: uid, createdAt: FieldValue.serverTimestamp(),
    });
  }
  function expire(command, timestamp) {
    return command && !TERMINAL.has(command.status) && command.expiresAt <= timestamp
      ? { ...command, status: "expired", finishedAt: timestamp, result: "Orden expirada sin confirmación." }
      : command || null;
  }
  function cleanTelemetry(input, timestamp) {
    if (!input || typeof input !== "object" || Array.isArray(input)) return null;
    return {
      contentId: text(input.contentId, 128), title: text(input.title), type: text(input.type, 32),
      playlistId: text(input.playlistId, 128), playlistName: text(input.playlistName),
      state: ["playing", "loading", "paused", "error", "unavailable"].includes(input.state) ? input.state : "unavailable",
      appliedMode: input.appliedMode === "stream" ? "stream" : "cache",
      origin: ["cache", "stream", "mixed", "unknown"].includes(input.origin) ? input.origin : "unknown",
      positionSeconds: Number.isFinite(input.positionSeconds) ? Math.max(0, Math.min(input.positionSeconds, 864000)) : null,
      webUrl: /^https?:\/\//.test(input.webUrl) ? text(input.webUrl, 2000) : "",
      error: text(input.error), updatedAt: timestamp,
    };
  }

  async function pairing(request) {
    const data = request.data || {};
    if (data.action === "create") {
      const tokenHash = credential(data.token);
      const sessionId = id(data.sessionId);
      // A six digit code is only a local presence claim, never a player credential.
      // The private secret/token is generated by the setup browser before creation.
      for (let attempt = 0; attempt < 5; attempt += 1) {
        const code = `AES-${randomInt(100000, 1000000)}`;
        const codeRef = db.collection(PAIRS).doc(code);
        const sessionRef = db.collection(PAIRS).doc(sessionId);
        try {
          await db.runTransaction(async (tx) => {
            const [codeDoc, sessionDoc] = await Promise.all([tx.get(codeRef), tx.get(sessionRef)]);
            if (sessionDoc.exists) fail("already-exists", "Sesión ya creada.");
            if (codeDoc.exists && codeDoc.data().expiresAt > now()) fail("aborted", "Código ocupado.");
            const expiresAt = now() + 600000;
            tx.set(codeRef, { sessionId, expiresAt });
            tx.create(sessionRef, { tokenHash, code, status: "pending", expiresAt, createdAt: now() });
          });
          return { id: sessionId, code, status: "pending", expiresAt: now() + 600000 };
        } catch (error) {
          if (error.code !== "aborted") throw error;
        }
      }
      fail("resource-exhausted", "No se pudo generar código. Reintenta.");
    }
    if (data.action !== "poll") fail("invalid-argument", "Acción desconocida.");
    const session = (await db.collection(PAIRS).doc(id(data.sessionId)).get()).data();
    if (!session || session.tokenHash !== credential(data.token)) fail("permission-denied", "Sesión inválida.");
    return {
      id: data.sessionId, code: session.code, deviceId: session.deviceId || "",
      status: session.expiresAt <= now() && session.status !== "claimed" ? "expired" : session.status,
      expiresAt: session.expiresAt,
    };
  }

  // Published snapshots are already normalized by the existing room publication flow.
  // Compose their device-specific manifest inside the same identity transaction. The
  // same plantel guard serializes this operation with publication and device edits.
  async function prepareRooms(tx, device) {
    const plantel = String(device.plantel || "").trim();
    const guardRef = db.collection("digitalSignageRoomConfigs").doc(encodeURIComponent(plantel));
    const [guard, published] = await Promise.all([
      tx.get(guardRef),
      tx.get(db.collection("digitalSignageRoomLayouts").where("publishedPlantel", "==", plantel).limit(101)),
    ]);
    if (published.size > 100) fail("resource-exhausted", "El plantel supera el límite de acomodos publicados.");
    const layouts = published.docs.map((entry) => entry.data().publishedSnapshot)
      .filter((snapshot) => snapshot && snapshot.active !== false && snapshot.plantel === plantel)
      .map((snapshot) => ({ ...snapshot, displayRules: (snapshot.displayRules || []).filter((rule) =>
        rule.active !== false && (!rule.deviceIds?.length || rule.deviceIds.includes(device.id))) }))
      .filter((snapshot) => snapshot.displayRules.length > 0)
      .sort((a, b) => String(a.id).localeCompare(String(b.id)));
    const manifest = { version: 1, deviceToken: device.id, plantel,
      timezone: layouts[0]?.timezone || "America/Tijuana", active: true, layouts, updatedAt: now() };
    if (Buffer.byteLength(JSON.stringify(manifest)) > 900 * 1024) fail("resource-exhausted", "Manifiesto de acomodos demasiado grande.");
    return () => {
      tx.set(db.collection("digitalSignageRoomDisplays").doc(device.id), { ...manifest, updatedAt: FieldValue.serverTimestamp() });
      if (guard.exists) tx.update(guardRef, { publicationRevision: (Number(guard.data().publicationRevision) || 0) + 1 });
      else tx.create(guardRef, { plantel, timezone: "America/Tijuana", rooms: [], teacherNames: [], publicationRevision: 1 });
    };
  }

  async function claim(request) {
    const uid = await admin(request);
    const data = request.data || {};
    const code = String(data.code || "").trim().toUpperCase().replace(/^([0-9]{6})$/, "AES-$1");
    if (!/^AES-[0-9]{6}$/.test(code)) fail("invalid-argument", "Código inválido.");
    const targetId = data.deviceId ? id(data.deviceId) : randomUUID();
    const deviceRef = db.collection(DEVICES).doc(targetId);
    const runtimeRef = db.collection(RUNTIME).doc(targetId);
    const result = await db.runTransaction(async (tx) => {
      const codeDoc = await tx.get(db.collection(PAIRS).doc(code));
      if (!codeDoc.exists || codeDoc.data().expiresAt <= now()) fail("failed-precondition", "Código inválido o expirado.");
      const pairRef = db.collection(PAIRS).doc(codeDoc.data().sessionId);
      const [pairDoc, deviceDoc, runtimeDoc] = await Promise.all([tx.get(pairRef), tx.get(deviceRef), tx.get(runtimeRef)]);
      const pair = pairDoc.data();
      const runtime = runtimeDoc.data() || {};
      if (!pair || pair.status !== "pending" || pair.expiresAt <= now()) fail("failed-precondition", "Código expirado o ya usado.");
      if (data.deviceId && !deviceDoc.exists) fail("not-found", "Pantalla no encontrada.");
      if (data.deviceId && deviceDoc.data().active === false) fail("failed-precondition", "Activa la pantalla antes de revincular.");
      const identityRef = db.collection(IDENTITIES).doc(pair.tokenHash);
      const identity = await tx.get(identityRef);
      if (identity.exists) fail("already-exists", "Identidad ya vinculada.");
      if (!data.deviceId && deviceDoc.exists) fail("already-exists", "Pantalla ya existente.");
      const roomDevice = deviceDoc.exists ? { ...deviceDoc.data(), id: targetId } : {
        id: targetId, plantel: text(data.device?.plantel).trim(),
      };
      if (!roomDevice.plantel) fail("invalid-argument", "Completa el plantel.");
      const commitRooms = await prepareRooms(tx, roomDevice);
      const generation = (runtime.generation || 0) + 1;
      if (runtime.credentialHash) tx.delete(db.collection(IDENTITIES).doc(runtime.credentialHash));
      tx.create(identityRef, { deviceId: targetId, generation });
      tx.set(runtimeRef, {
        generation, credentialHash: pair.tokenHash, mode: runtime.mode || deviceDoc.data()?.playbackMode || "cache",
        command: null, monitor: null, telemetry: null, lastSeenAt: 0,
      });
      if (deviceDoc.exists) {
        tx.update(deviceRef, {
          deviceToken: "", secureControl: true, updatedAt: FieldValue.serverTimestamp(),
          lastSeenAt: null, lastSeenMillis: 0,
        });
      } else {
        const name = text(data.device?.name).trim();
        const plantel = text(data.device?.plantel).trim();
        const location = text(data.device?.location).trim();
        if (!name || !plantel || !location) fail("invalid-argument", "Completa nombre, plantel y ubicación.");
        tx.create(deviceRef, {
          name, plantel, location, deviceToken: "", secureControl: true,
          assignedPlaylistId: text(data.device?.assignedPlaylistId, 128), active: true,
          createdAt: FieldValue.serverTimestamp(), updatedAt: FieldValue.serverTimestamp(),
          createdById: uid, createdBy: uid, lastSeenAt: null, lastSeenMillis: 0,
        });
      }
      tx.update(pairRef, { status: "claimed", deviceId: targetId, claimedBy: uid, claimedAt: now() });
      commitRooms();
      audit(tx, data.deviceId ? "revincular dispositivo" : "vincular pantalla por código", targetId, uid, { generation });
      return { deviceId: targetId, id: targetId };
    });
    return result;
  }

  async function control(request) {
    const uid = await admin(request);
    const data = request.data || {};
    if (data.action === "claim" || data.action === "rebind") return claim(request);
    const deviceId = id(data.deviceId);
    const runtimeRef = db.collection(RUNTIME).doc(deviceId);
    return db.runTransaction(async (tx) => {
      const [runtimeDoc, deviceDoc] = await Promise.all([tx.get(runtimeRef), tx.get(db.collection(DEVICES).doc(deviceId))]);
      if (!deviceDoc.exists) fail("not-found", "Pantalla no encontrada.");
      const runtime = runtimeDoc.data();
      const timestamp = now();
      const device = deviceDoc.data();
      const active = device.active !== false;
      if (!runtime) {
        if (data.action === "status") {
          // Legacy heartbeat describes connectivity, not permission to control the player.
          const reported = Number(device.lastSeenMillis) || device.lastSeenAt?.toMillis?.() || 0;
          const lastSeenAt = Number.isFinite(reported) ? reported : 0;
          return {
            enabled: false, active, mode: device.playbackMode === "stream" ? "stream" : "cache",
            lastSeenAt, online: active && lastSeenAt > timestamp - CONNECTION_MAX_AGE_MS,
            telemetry: null, command: null, monitor: null,
          };
        }
        fail("failed-precondition", "Revincula el dispositivo para habilitar el control seguro.");
      }
      const command = expire(runtime.command, timestamp);
      if (data.action === "status") {
        if (command?.status !== runtime.command?.status) {
          tx.update(runtimeRef, { command });
          if (command) tx.set(runtimeRef.collection("commands").doc(command.id), command);
        }
        const liveMonitor = runtime.monitor?.expiresAt > timestamp && runtime.monitor.owner === uid ? runtime.monitor : null;
        return {
          enabled: true, active, mode: runtime.mode, command, lastSeenAt: runtime.lastSeenAt || 0,
          telemetry: runtime.telemetry || null,
          online: active && runtime.lastSeenAt > timestamp - CONNECTION_MAX_AGE_MS,
          monitor: liveMonitor ? { sessionId: liveMonitor.sessionId, expiresAt: liveMonitor.expiresAt,
            frame: liveMonitor.frame || null, captureError: liveMonitor.captureError || "" } : null,
        };
      }
      if (!active) fail("failed-precondition", "La pantalla está inactiva.");
      if (data.action === "mode") {
        if (!["cache", "stream"].includes(data.mode)) fail("invalid-argument", "Modo inválido.");
        tx.update(runtimeRef, { mode: data.mode });
        tx.update(deviceDoc.ref, { playbackMode: data.mode, updatedAt: FieldValue.serverTimestamp() });
        audit(tx, "cambiar modo de reproducción", deviceId, uid, { mode: data.mode });
        return { mode: data.mode };
      }
      if (["monitor_start", "monitor_stop"].includes(data.action)) {
        const sessionId = id(data.sessionId);
        const current = runtime.monitor;
        if (data.action === "monitor_stop") {
          if (current?.owner === uid && current.sessionId === sessionId) tx.update(runtimeRef, { monitor: null });
          return { stopped: true };
        }
        if (current?.expiresAt > timestamp && (current.owner !== uid || current.sessionId !== sessionId)) {
          fail("already-exists", "Otra sesión está supervisando esta pantalla.");
        }
        const monitor = { sessionId, owner: uid, expiresAt: timestamp + LEASE,
          frame: current?.sessionId === sessionId ? current.frame || null : null,
          captureError: current?.sessionId === sessionId ? current.captureError || "" : "" };
        tx.update(runtimeRef, { monitor });
        if (current?.sessionId !== sessionId || current.expiresAt <= timestamp) audit(tx, "ver pantalla", deviceId, uid, { sessionId });
        return { sessionId, expiresAt: monitor.expiresAt };
      }
      if (data.action !== "command" || !TYPES.has(data.type)) fail("invalid-argument", "Comando no permitido.");
      const requestId = id(data.requestId);
      const historyRef = runtimeRef.collection("commands").doc(requestId);
      const previous = await tx.get(historyRef);
      if (previous.exists) {
        if (previous.data().type !== data.type || previous.data().createdBy !== uid) fail("already-exists", "Identificador ya utilizado.");
        return { command: command?.id === requestId ? command : previous.data() };
      }
      if (command && !TERMINAL.has(command.status)) fail("failed-precondition", "Existe una orden pendiente de confirmación.");
      if (command && timestamp - command.createdAt < 10000) fail("resource-exhausted", "Espera antes de enviar otra orden.");
      const payload = {};
      if (data.type.startsWith("web_")) {
        if (runtime.monitor?.expiresAt <= timestamp || runtime.monitor?.owner !== uid || runtime.monitor?.sessionId !== data.sessionId) {
          fail("permission-denied", "Abre una sesión de monitoreo para controlar esta página.");
        }
        if (runtime.lastSeenAt <= timestamp - 75000 || runtime.telemetry?.type !== "web") fail("failed-precondition", "No hay una página web activa confirmada.");
        payload.expectedContentId = runtime.telemetry.contentId;
        payload.expectedWebUrl = runtime.telemetry.webUrl;
        if (data.type === "web_scroll") {
          if (!["up", "down"].includes(data.payload?.direction)) fail("invalid-argument", "Dirección inválida.");
          payload.direction = data.payload.direction;
        }
        if (data.type === "web_navigate") {
          const path = data.payload?.path;
          if (typeof path !== "string" || !/^\/(?!\/)/.test(path) || path.includes("\\") ||
            [...path].some((char) => char.charCodeAt(0) < 32) || path.length > 1500) fail("invalid-argument", "Usa una ruta del mismo sitio.");
          payload.path = path;
        }
      }
      const nextCommand = {
        id: requestId, type: data.type, payload, status: "pending", createdAt: timestamp,
        expiresAt: timestamp + TTL, createdBy: uid, generation: runtime.generation,
        sessionId: data.type.startsWith("web_") ? data.sessionId : "",
      };
      tx.update(runtimeRef, { command: nextCommand });
      tx.create(historyRef, nextCommand);
      audit(tx, `comando ${data.type}`, deviceId, uid, { commandId: requestId });
      return { command: nextCommand };
    });
  }

  async function exchange(request) {
    const data = request.data || {};
    const tokenHash = credential(data.token);
    return db.runTransaction(async (tx) => {
      const identityDoc = await tx.get(db.collection(IDENTITIES).doc(tokenHash));
      if (!identityDoc.exists) fail("permission-denied", "Identidad sustituida o no vinculada.");
      const identity = identityDoc.data();
      const deviceRef = db.collection(DEVICES).doc(identity.deviceId);
      const runtimeRef = db.collection(RUNTIME).doc(identity.deviceId);
      const [runtimeDoc, deviceDoc, roomDoc] = await Promise.all([
        tx.get(runtimeRef), tx.get(deviceRef), tx.get(db.collection("digitalSignageRoomDisplays").doc(identity.deviceId)),
      ]);
      const runtime = runtimeDoc.data();
      if (!runtime || runtime.credentialHash !== tokenHash || runtime.generation !== identity.generation || !deviceDoc.exists) {
        fail("permission-denied", "Identidad sustituida.");
      }
      const device = deviceDoc.data();
      const timestamp = now();
      const view = { ...device, id: identity.deviceId, playbackMode: runtime.mode };
      // Callable serialization must not expose Admin Timestamp instances or credentials.
      delete view.createdAt; delete view.updatedAt; delete view.lastSeenAt;
      const response = { device: view, mode: runtime.mode, command: null, monitor: null };
      const room = roomDoc.data();
      const roomAllowed = device.active !== false && room?.active !== false && room?.plantel === device.plantel;
      response.roomRevision = roomAllowed ? String(roomDoc.updateTime.toMillis()) : "";
      if (data.roomRevision !== response.roomRevision) {
        response.roomManifest = roomAllowed ? {
          ...room, updatedAt: room.updatedAt?.toMillis?.() || Number(room.updatedAt) || 0,
        } : null;
      }
      if (device.active === false || data.readOnly === true) return response;
      const playerSessionId = id(data.playerSessionId);
      let command = expire(runtime.command, timestamp);
      if (command && command.type.startsWith("web_") && !TERMINAL.has(command.status) &&
        (runtime.monitor?.expiresAt <= timestamp || runtime.monitor?.sessionId !== command.sessionId)) {
        command = { ...command, status: "expired", result: "Sesión de control finalizada.", finishedAt: timestamp };
      }
      const ack = data.ack;
      if (ack && command?.id === ack.id && command.status === "received" &&
        command.receivedBy === playerSessionId && ["executed", "failed"].includes(ack.status)) {
        command = { ...command, status: ack.status, result: text(ack.result), finishedAt: timestamp };
      }
      if (command?.status === "pending") {
        command = { ...command, status: "received", receivedAt: timestamp, receivedBy: playerSessionId };
        response.command = command;
      } else if (command?.status === "received" && command.receivedBy === playerSessionId) {
        // Retry delivery after a lost HTTP response; the player deduplicates execution by ID.
        response.command = command;
      }
      const changes = {};
      if (JSON.stringify(command) !== JSON.stringify(runtime.command || null)) {
        changes.command = command;
        if (command) tx.set(runtimeRef.collection("commands").doc(command.id), command);
      }
      // Server timestamps and rate bounds determine freshness, never client wall clock.
      const canReport = !runtime.lastSeenAt || timestamp - runtime.lastSeenAt >= 8000;
      if (canReport) {
        changes.lastSeenAt = timestamp;
        const telemetry = cleanTelemetry(data.telemetry, timestamp);
        if (telemetry) changes.telemetry = telemetry;
        if (!runtime.publicHeartbeatAt || timestamp - runtime.publicHeartbeatAt >= 30000) {
          changes.publicHeartbeatAt = timestamp;
          tx.update(deviceRef, { lastSeenMillis: timestamp, lastSeenAt: FieldValue.serverTimestamp() });
        }
      }
      if (runtime.monitor?.expiresAt > timestamp) {
        response.monitor = { sessionId: runtime.monitor.sessionId, expiresAt: runtime.monitor.expiresAt };
        if (data.monitorSessionId === runtime.monitor.sessionId &&
          (!runtime.monitor.lastFrameAt || timestamp - runtime.monitor.lastFrameAt >= 8000)) {
          const frame = data.frame;
          if (frame && typeof frame.dataUrl === "string" && frame.dataUrl.length <= 100000 &&
            /^data:image\/jpeg;base64,[A-Za-z0-9+/=]+$/.test(frame.dataUrl) &&
            Number.isFinite(frame.capturedAt) && Math.abs(timestamp - frame.capturedAt) <= 20000) {
            changes.monitor = { ...runtime.monitor, frame: { dataUrl: frame.dataUrl, capturedAt: timestamp }, captureError: "", lastFrameAt: timestamp };
          } else if (data.captureError) {
            changes.monitor = { ...runtime.monitor, frame: null, captureError: text(data.captureError), lastFrameAt: timestamp };
          }
        }
      } else if (runtime.monitor) changes.monitor = null;
      if (Object.keys(changes).length) tx.update(runtimeRef, changes);
      return response;
    });
  }
  return { pairing, control, exchange };
}

module.exports = { createSignageHandlers };
