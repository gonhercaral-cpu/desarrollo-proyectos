test("estados distinguen pendiente, procesamiento, procesador compatible y errores de Nube AES", () => {
  const presentation = { id: "p", name: "Clase", kind: "presentation", mimeType: "application/vnd.google-apps.presentation" };
  assert.equal(getResourceStatus(presentation).key, "pending");
  assert.equal(getResourceStatus(presentation).label, "Pendiente de procesar");
  assert.equal(getResourceStatus({ ...presentation, processing: { state: "processing" } }).label, "Procesando");
  assert.equal(getProcessingStatus({ ...presentation, processing: { state: "ready", processorVersion: "obsolete" } }), "pending");
  const processed = { ...presentation, processing: { state: "ready", processorVersion: "google-slides-builds-png-v2", pageCount: 20 } };
  assert.equal(getResourceStatus(processed).label, "Procesada");
  assert.equal(getResourceStatus(processed).detail, "20 diapositivas");
  assert.equal(getResourceStatus(processed, { status: "changed" }).key, "changed");
  assert.equal(getResourceStatus(processed, { status: "unavailable" }).key, "unavailable");
  assert.equal(getResourceStatus(processed, { status: "error", message: "Original bloqueado" }).detail, "Original bloqueado");
  assert.equal(getResourceStatus({ ...presentation, processing: { state: "failed" } }).key, "error");
  const image = { name: "Foto.png", kind: "image", mimeType: "image/png" };
  assert.equal(getProcessingStatus(image), "none", "imagen disponible no se cuenta como Office procesado");
  assert.equal(getResourceStatus(image).label, "Actualizado");
  assert.equal(getFileTypeCategory({ name: "Hoja.pdf", mimeType: "application/pdf", kind: "document" }), "pdf");
});

